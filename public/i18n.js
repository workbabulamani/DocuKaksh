const STRINGS = { en, hi, bn, te, ta, mr, ur, es, fr, de, zh, ar };
let current = 'en';

export function setLanguage(code) {
  current = STRINGS[code] ? code : 'en';
  const meta = LANGUAGES.find((l) => l.code === current);
  document.documentElement.lang = current;
  document.documentElement.dir = meta.dir;
}

// Looks a text up in the chosen language, then English. {name} placeholders are filled from vars.
export function t(key, vars = {}) {
  const text = STRINGS[current]?.[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

// Applies translations to elements marked with data-i18n (text) or data-i18n-title / -placeholder / -aria.
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
